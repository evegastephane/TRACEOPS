async function api(context, path, body, org) {
 const r = await context.request.fetch(base + '/api/v1/' + path, { method: body === undefined ? 'GET' : 'POST', headers: { 'X-Traceops':'request', Origin:base, ...(org ? { 'X-Organization-Id':org } : {}) }, ...(body === undefined ? {} : { data:body }) });
 assert.ok(r.ok(), `${path}: ${r.status()}`); return r.json();
}
